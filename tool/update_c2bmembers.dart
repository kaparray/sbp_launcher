// Обновляет встроенный снимок lib/data/c2bmembers_data.dart из реестра НСПК.
//
//   dart run tool/update_c2bmembers.dart [--url=<url> | --file=<path>]
//
// Локальные иконки (поле icon) переносятся из текущего снимка по schema.
import 'dart:convert';
import 'dart:io';

import 'package:sbp/data/c2bmembers_data.dart';

const _defaultUrl = 'https://qr.nspk.ru/proxyapp/c2bmembers.json';
const _output = 'lib/data/c2bmembers_data.dart';

/// Поля, которые попадают в снимок. Остальные поля ответа игнорируются.
const _stringFields = ['bankName', 'logoURL', 'schema', 'package_name', 'webClientUrl'];
const _boolFields = ['isWebClientActive'];

Future<void> main(List<String> args) async {
  final options = {
    for (final arg in args)
      if (arg.startsWith('--') && arg.contains('='))
        arg.substring(2, arg.indexOf('=')): arg.substring(arg.indexOf('=') + 1),
  };

  final body = options['file'] != null
      ? await File(options['file']!).readAsString()
      : await _download(Uri.parse(options['url'] ?? _defaultUrl));

  final json = jsonDecode(body) as Map<String, dynamic>;
  final dictionary = (json['dictionary'] as List).cast<Map<String, dynamic>>();

  final icons = {
    for (final bank in (c2bmembersData['dictionary'] as List).cast<Map<String, Object?>>())
      if (bank['icon'] != null) bank['schema']: bank['icon'],
  };

  final iconsByPackage = <Object?, Object?>{};
  for (final bank in (c2bmembersData['dictionary'] as List).cast<Map<String, Object?>>()) {
    if (bank['icon'] != null && bank['package_name'] != null) {
      iconsByPackage.putIfAbsent(bank['package_name'], () => bank['icon']);
    }
  }

  final packageCount = <Object?, int>{};
  for (final bank in dictionary) {
    packageCount.update(bank['package_name'], (count) => count + 1, ifAbsent: () => 1);
  }

  final banks = <Map<String, Object>>[];
  for (final bank in dictionary) {
    final schema = bank['schema'];
    if (schema is! String || schema.isEmpty) continue;
    final entry = <String, Object>{};
    for (final field in _stringFields) {
      final value = bank[field];
      if (value is String && value.isNotEmpty) entry[field] = value;
    }
    for (final field in _boolFields) {
      if (bank[field] is bool) entry[field] = bank[field] as bool;
    }
    // банк может сменить schema (ВТБ: bank100000000005 -> bank110000000005), тогда ищем иконку по пакету.
    // White-label пакеты (один пакет на несколько банков) пропускаем, иначе банки получат чужую иконку.
    final packageName = bank['package_name'];
    final icon = icons[schema] ?? (packageCount[packageName] == 1 ? iconsByPackage[packageName] : null);
    if (icon != null) entry['icon'] = icon;
    banks.add(entry);
  }

  final date = DateTime.now().toIso8601String().substring(0, 10);
  final encoded = const JsonEncoder.withIndent('  ').convert({'version': json['version'] ?? '', 'dictionary': banks})
      // в строках Dart символ $ означает интерполяцию
      .replaceAll(r'$', r'\$');
  await File(_output).writeAsString('''
// GENERATED by tool/update_c2bmembers.dart - не редактировать вручную.

/// Дата снимка встроенного списка банков [c2bmembersData]
const c2bmembersDataDate = '$date';

/// Снимок https://qr.nspk.ru/proxyapp/c2bmembers.json от [c2bmembersDataDate].
/// Используется как fallback, если сервер и кэш недоступны.
final Map<String, dynamic> c2bmembersData = $encoded;
''');

  stdout.writeln('$_output: ${banks.length} banks, ${banks.where((b) => b['icon'] != null).length} with local icons');
}

Future<String> _download(Uri url) async {
  final client = HttpClient()..connectionTimeout = const Duration(seconds: 30);
  try {
    final response = await (await client.getUrl(url)).close();
    if (response.statusCode != 200) {
      throw HttpException('HTTP ${response.statusCode}', uri: url);
    }
    return await response.transform(utf8.decoder).join();
  } finally {
    client.close();
  }
}
